export function getFallbackPassage({ universe = null, difficulty = null } = {}) {
  let filtered = CURATED_PASSAGES;

  if (universe && universe.toLowerCase() !== 'all') {
    const uniLower = universe.toLowerCase();
    const uniMatches = filtered.filter((p) => p.universe.toLowerCase() === uniLower);
    if (uniMatches.length > 0) {
      filtered = uniMatches;
    }
  }

  if (difficulty && ['easy', 'medium', 'hard'].includes(difficulty.toLowerCase())) {
    const diffLower = difficulty.toLowerCase();
    const diffMatches = filtered.filter((p) => p.difficulty.toLowerCase() === diffLower);
    if (diffMatches.length > 0) {
      filtered = diffMatches;
    }
  }

  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex];
}

export function getFallbackUniverses() {
  const counts = {};
  CURATED_PASSAGES.forEach((p) => {
    counts[p.universe] = (counts[p.universe] || 0) + 1;
  });

  return Object.entries(counts).map(([universe, count]) => ({ universe, count }));
}
